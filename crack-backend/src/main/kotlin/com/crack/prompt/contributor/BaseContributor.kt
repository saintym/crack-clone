            "- 분량은 한 응답에 약 ${n(chars.min)}~${n(chars.max)}자를 목표로 한다. " +
                "장면이 짧게 끝나야 할 때는 더 짧아도 되지만, ${n(chars.hardMax)}자를 넘기지 마라."

