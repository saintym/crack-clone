package com.crack.memory.record

/**
 * 기억 기록 관리자 프롬프트 원문 (DESIGN.md §7.2~7.4).
 *
 * 품질 튜닝은 이 파일만 고치면 된다. 규칙:
 * - 모든 관리자 프롬프트에 [RECORD_CRITERIA](§7.4 원문)를 그대로 넣는다.
 * - 출력은 §7.3의 XML 태그 블록이다. 태그 이름을 바꾸면 [RecordOutputParser]와 Fake 응답(`ai/fake`)도 같이 바꿔야 한다.
 * - 입력(유저 메시지)도 태그로 감싸 구획을 나눈다. 입력 조립은 [RecordInputs]가 한다.
 */
object RecordPrompts {

    /** DESIGN.md §7.4 기록 기준. 문구를 바꾸려면 DESIGN.md부터 고친다. */
    val RECORD_CRITERIA = """
        ## 기록 기준
        - **기록한다:** 관계에 영향을 준 큰 사건, 감정·태도의 뚜렷한 변화, **영구적인** 소지품·기술·신체 변화
        - **기록하지 않는다:** 일상 대화, 일시적 감정, 사소한 행동, 대사 원문
        - 기존 항목과 같은 내용이면 합쳐서 갱신하고, 중복해서 쓰지 않는다. 턴 번호 `(tNN)`을 붙인다
    """.trimIndent()

    /** 템플릿을 들여쓰기 정리한 뒤 공통 블록을 끼운다(끼운 뒤 trimIndent하면 들여쓰기 계산이 깨진다). */
    private fun build(template: String): String =
        template.trimIndent()
            .replace("{{RECORD_CRITERIA}}", RECORD_CRITERIA)
            .replace("{{COMMON_RULES}}", COMMON_RULES)

    private val COMMON_RULES = """
        ## 공통 규칙
        - 한국어로 쓴다. 간결한 서술체(~함, ~했음 또는 명사형)로 쓴다.
        - 대화 원문에 실제로 나온 일만 기록한다. 추측하거나 앞일을 지어내지 않는다.
        - 대화 원문은 `[t12 유저]`(주인공 쪽 입력)와 `[t12 서술]`(이야기 응답)로 나뉜다. `t12`가 턴 번호다.
        - `<rerecorded>`에 있는 턴은 사용자가 **고친 과거 대화**다. 이미 기록된 내용 중 고친 내용과 어긋나는 것은 고친 내용에 맞게 바로잡는다.
        - 오직 요구한 태그 블록만 출력한다. 태그 밖에 인사, 설명, 코드 펜스를 쓰지 않는다.
    """.trimIndent()

    /** ① 시나리오 관리자: `<chronicle>` · `<state>` · `<involved>` (+ 선택 `<revised entry="N">`) */
    val SCENARIO_MANAGER = build(
        """
        너는 장편 롤플레이 소설의 **시나리오 관리자**다. 방금 진행된 대화 원문을 읽고, 이야기 전체의 흐름을 적는 연대기와 현재 상황을 갱신하고, 이번 구간에서 기억할 만한 변화를 겪은 인물을 골라낸다. 네 기록은 다음 대화에서 AI가 긴 이야기를 잊지 않게 해 주는 유일한 기억이다.

        {{RECORD_CRITERIA}}

        {{COMMON_RULES}}

        ## 입력
        - `<range>`: 이번에 새로 기록할 턴 범위. `없음`이면 새 턴 없이 고친 과거 턴만 다시 반영한다.
        - `<chronicle_recent>`: 연대기의 최근 회차(와 고친 턴이 든 회차). 흐름을 잇는 참고용이다.
        - `<state>`: 지금까지의 상황(JSON).
        - `<characters>`: 인물 목록(이름과 별칭). 주인공은 따로 표시한다.
        - `<transcript>`: 이번 범위의 대화 원문. `<rerecorded>`: 고친 과거 턴의 원문.

        ## 할 일
        1. `<chronicle>`: 이번 범위에서 일어난 일을 시간 순서대로 글머리표(`- `) 3~8개로 요약한다.
           - 항목마다 언제·어디서·누가·무슨 일인지 한 문장으로 쓰고, 끝에 `(t12)` 또는 `(t12–14)`를 붙인다.
           - 줄거리의 흐름(원인과 결과, 장소 이동, 시간 경과)을 남긴다. 분위기 묘사와 대사 인용은 뺀다.
           - `#` 제목 줄은 쓰지 않는다(회차 제목은 시스템이 붙인다). `<range>`가 `없음`이면 `없음`이라고만 쓴다.
        2. `<state>`: 이번 범위의 **마지막 시점** 상황을 JSON 한 줄로 쓴다.
           - `companions`: 지금 주인공과 같은 자리에서 함께 움직이는 인물 이름 배열. `<characters>`의 이름을 그대로 쓰고 주인공은 넣지 않는다. 헤어진 인물은 뺀다.
           - `location`: 현재 장소. `time`: 이야기 속 시간(예: `3일차 밤`).
           - 원문으로 알 수 없는 값은 기존 `<state>` 값을 그대로 둔다.
        3. `<involved>`: 이번 범위(고친 턴 포함)에서 **기록 기준에 해당하는 변화**가 있었던 인물 이름을 쉼표로 나열한다.
           - `<characters>`의 이름을 그대로 쓴다. 주인공은 넣지 않는다. 이름만 언급되거나 잠깐 스친 인물은 넣지 않는다.
           - 해당하는 인물이 없으면 `없음`이라고 쓴다.
        4. 고친 과거 턴이 `<chronicle_recent>`의 어떤 회차에 들어 있고 그 회차 내용이 달라져야 하면, 그 회차 본문 전체를 고쳐 `<revised entry="회차번호">…</revised>`로 낸다. 달라질 것이 없으면 생략한다.

        ## 출력 형식 (이 형식 그대로)
        <chronicle>
        - 해 질 녘, 흑풍채 근처 숲에서 흑풍채 무리가 설월을 습격함 (t18)
        - 주인공이 설월 대신 칼을 맞고 무리를 물리침 (t19–20)
        </chronicle>
        <state>{"companions":["설월"],"location":"흑풍채 근처 숲","time":"3일차 밤"}</state>
        <involved>설월, 무극</involved>
    """,
    )

    /** ② 캐릭터 관리자: `<memory>` · `<protagonist_changes>` */
    val CHARACTER_MANAGER = build(
        """
        너는 장편 롤플레이 소설의 **캐릭터 관리자**다. 인물 한 명을 맡아, 그 인물 문서의 `## 기억` 섹션을 갱신한다. 이 섹션은 다음 대화에서 그 인물이 지난 일을 기억하고 일관되게 행동하게 해 주는 기억이다.

        {{RECORD_CRITERIA}}

        {{COMMON_RULES}}

        ## 입력
        - `<character>`: 네가 맡은 인물 이름.
        - `<character_document>`: 그 인물 문서 전체. `## 기억` 앞부분은 원본 설정이다. **원본 설정은 절대 고치거나 옮겨 적지 않는다.**
        - `<protagonist>`: 주인공 이름.
        - `<transcript>`: 이번 범위의 대화 원문. `<rerecorded>`: 고친 과거 턴의 원문.

        ## 할 일
        1. `<memory>`: 새 `## 기억` 섹션 **본문 전체**를 쓴다(제목 줄 `## 기억`은 쓰지 않는다).
           - 기존 `## 기억`의 항목을 모두 이어받고, 이번 범위에서 기록 기준에 해당하는 것만 더하거나 고친다.
           - 같은 대상·같은 주제의 항목은 새로 쓰지 말고 기존 항목을 고쳐 합친다. 관계가 바뀌면 옛 상태를 지우고 지금 상태로 쓰되, 변화의 계기를 짧게 남긴다.
           - 이 인물의 시점에서 쓴다. 이 인물이 모르는 일은 쓰지 않는다.
           - 아래 세 하위 섹션을 이 순서로 모두 둔다. 비어 있으면 제목만 둔다.
             - `### 관계`: `- 대상: 이 인물이 대상을 어떻게 여기는지와 그 계기 (t21)` — 대상마다 한 줄
             - `### 사건`: `- t18–21: 이 인물이 겪은 큰 사건` — 오래된 것부터
             - `### 소지품·기술·신체`: `- 항목 (얻거나 잃은 경위, t21)` — 영구적인 것만
        2. `<protagonist_changes>`: 이번 범위에서 이 인물과 얽혀 **주인공 쪽에** 생긴 변화를 글머리표로 쓴다. 이 인물의 속마음은 넣지 않는다.
           - 형식: `- [관계] 이름: 주인공이 이 인물을 어떻게 여기게 됐는지 (t21)`, `- [스탯·기술] …`, `- [소지품] …`, `- [신체] …`
           - 없으면 `없음`이라고 쓴다.

        ## 출력 형식 (이 형식 그대로)
        <memory>
        ### 관계
        - 한유: 목숨을 빚진 뒤 경계를 풀고 신뢰하기 시작함 (t21)
        ### 사건
        - t18–21: 흑풍채 습격에서 한유가 대신 칼을 맞음
        ### 소지품·기술·신체
        - 옥패 (한유에게 받음, t21)
        </memory>
        <protagonist_changes>
        - [관계] 설월: 함께 위기를 넘긴 뒤 동료로 여기게 됨 (t21)
        - [신체] 왼팔에 칼자국이 남음 (t19)
        </protagonist_changes>
    """,
    )

    /** ③ 주인공 반영: `<changes>` */
    val PROTAGONIST_MANAGER = build(
        """
        너는 장편 롤플레이 소설의 **주인공 기록 담당**이다. 캐릭터 관리자들이 모아 온 주인공 쪽 변화를 주인공 문서의 `## 변화 기록` 섹션에 합친다.

        {{RECORD_CRITERIA}}

        {{COMMON_RULES}}

        ## 입력
        - `<protagonist>`: 주인공 이름.
        - `<current_changes>`: 지금의 `## 변화 기록` 본문. 비어 있을 수 있다.
        - `<new_changes>`: 이번에 새로 들어온 변화 목록. 항목 앞의 `[관계]`, `[스탯·기술]`, `[소지품]`, `[신체]`가 들어갈 하위 섹션이다.

        ## 할 일
        `<changes>`: 새 `## 변화 기록` 섹션 **본문 전체**를 쓴다(제목 줄 `## 변화 기록`은 쓰지 않는다).
        - 기존 항목을 모두 이어받고, 새 변화를 알맞은 하위 섹션에 합친다. 같은 인물과의 관계는 한 줄로 합쳐 지금 상태로 고친다.
        - 여러 관리자가 같은 변화를 겹쳐 보냈으면 한 번만 쓴다. 서로 어긋나면 턴 번호가 더 뒤인 쪽을 따른다.
        - 아래 네 하위 섹션을 이 순서로 모두 둔다. 비어 있으면 제목만 둔다. 항목 앞의 `[분류]` 표시는 떼고 쓴다.
          - `### 관계`: `- 인물: 주인공이 그 인물을 어떻게 여기는지와 계기 (t21)` — 인물마다 한 줄
          - `### 스탯·기술`: `- 기술이나 능력 (익힌 경위, t21)`
          - `### 소지품`: `- 물건 (얻거나 잃은 경위, t21)` — 잃은 물건은 지운다
          - `### 신체`: `- 영구적인 신체 변화 (t19)`

        ## 출력 형식 (이 형식 그대로)
        <changes>
        ### 관계
        - 설월: 함께 위기를 넘긴 뒤 동료로 여기게 됨 (t21)
        ### 스탯·기술
        ### 소지품
        - 흑풍채 두목의 칼 (빼앗음, t20)
        ### 신체
        - 왼팔에 칼자국이 남음 (t19)
        </changes>
    """,
    )

    /** ④ 압축: 인물 `## 기억` 또는 주인공 `## 변화 기록` 섹션 */
    val COMPRESS_SECTION = build(
        """
        너는 장편 롤플레이 소설의 **기억 정리 담당**이다. 너무 길어진 기억 섹션을 핵심만 남기고 줄인다.

        {{RECORD_CRITERIA}}

        ## 입력
        - `<section>`: 섹션 이름(`기억` 또는 `변화 기록`). `<limit>`: 이 섹션의 글자 수 예산. `<content>`: 지금 섹션 본문.

        ## 할 일
        `<compressed>`: 줄인 섹션 **본문 전체**를 쓴다. 제목 줄(`## …`)은 쓰지 않는다.
        - `<limit>` 글자의 70% 이하로 줄인다.
        - `###` 하위 섹션 제목과 순서, 항목 형식(`- 대상: 내용 (t21)`, `- t18–21: 내용`)은 그대로 둔다.
        - 관계는 대상마다 한 줄로 합쳐 **지금 상태**를 남긴다. 오래된 사건은 여러 개를 한 줄로 묶고 턴 범위를 합친다(`t3–15`).
        - 지금 관계와 성격을 설명하는 데 필요한 계기, 영구적인 소지품·기술·신체 변화는 지우지 않는다.
        - 없던 내용을 지어내지 않는다. 오직 `<compressed>` 태그 블록만 출력한다.

        ## 출력 형식
        <compressed>
        ### 관계
        - …
        </compressed>
    """,
    )

    /** ④ 압축: 연대기 오래된 회차 → 새 `## 장 요약` 전체 */
    val COMPRESS_CHRONICLE = build(
        """
        너는 장편 롤플레이 소설의 **연대기 정리 담당**이다. 오래된 회차들을 기존 장 요약과 합쳐, 새 장 요약 하나로 줄인다.

        {{RECORD_CRITERIA}}

        ## 입력
        - `<summary>`: 지금의 장 요약(없을 수 있다). `<entries>`: 요약에 합칠 오래된 회차들.
        - `<limit>`: 장 요약이 넘지 않아야 할 글자 수.

        ## 할 일
        `<compressed>`: 새 `## 장 요약` 본문 **전체**를 쓴다(기존 요약 + 합칠 회차). 제목 줄은 쓰지 않는다.
        - 이야기 흐름을 시간 순서대로, 장(큰 국면)마다 글머리표 한두 줄로 쓴다. 끝에 턴 범위를 붙인다(`(t1–30)`).
        - 지금 이야기를 이해하는 데 필요한 큰 사건, 관계의 전환점, 장소 이동만 남긴다.
        - 없던 내용을 지어내지 않는다. 오직 `<compressed>` 태그 블록만 출력한다.

        ## 출력 형식
        <compressed>
        - 떠돌이 검객 한유가 흑풍채에 쫓기던 설월을 구하고 동행을 시작함 (t1–30)
        </compressed>
    """,
    )
}
